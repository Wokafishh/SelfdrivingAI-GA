"""
Converts the Inventor export ("Bil komplett för webots.obj") into Webots-ready meshes.

The export is in millimeters, Y points down, +Z points forward and the wheels are part
of the same mesh. Webots wants meters, Z up and +X forward, and the wheels must be
separate meshes so they can spin on their HingeJoints. Writes to models/webots/:
  car_body.obj        everything except the wheels, origin on the floor under the wheel axle
  car_wheel_left.obj  left wheel (+Y side in Webots), origin at the wheel center
  car_wheel_right.obj right wheel (-Y side in Webots), origin at the wheel center
  car.mtl             the materials (missing texture maps removed)

Run again only if the Inventor model changes: python Train_RL/models/convert_car_model.py
"""

from pathlib import Path

MODEL_DIR = Path(__file__).resolve().parent
SOURCE_OBJ = MODEL_DIR / "Bil komplett för webots.obj"
SOURCE_MTL = MODEL_DIR / "Bil komplett för webots.mtl"
OUTPUT_DIR = MODEL_DIR / "webots"

# Inventor groups that make up each wheel (tire + rim)
WHEEL_GROUPS = {
    "car_wheel_right.obj": {"Solid1:11", "Solid1:12"},  # Inventor +X side
    "car_wheel_left.obj": {"Solid1:13", "Solid1:14"},   # Inventor -X side
}

# Reference points in Inventor coordinates (mm)
AXLE_Z = 39.0      # Wheel axle position along the driving direction
GROUND_Y = 44.05   # Lowest point of the wheels (the floor)
WHEEL_CENTER_X = 67.0
WHEEL_CENTER_Y = 11.5


def to_webots(x: float, y: float, z: float) -> tuple[float, float, float]:
    """Inventor (mm, Y down, Z forward) -> Webots robot frame (m, Z up, X forward)."""
    return (z - AXLE_Z) / 1000, -x / 1000, (GROUND_Y - y) / 1000


def rotate_normal(x: float, y: float, z: float) -> tuple[float, float, float]:
    return z, -x, -y


def read_obj(path: Path):
    vertices, texcoords, normals = [], [], []
    faces = []  # (group, material, [(v, vt, vn), ...]) with 0-based indices
    group, material = "default", None
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        parts = line.split()
        if not parts:
            continue
        tag = parts[0]
        if tag == "v":
            vertices.append(tuple(map(float, parts[1:4])))
        elif tag == "vt":
            texcoords.append(parts[1:])
        elif tag == "vn":
            normals.append(tuple(map(float, parts[1:4])))
        elif tag == "g":
            group = parts[1] if len(parts) > 1 else "default"
        elif tag == "usemtl":
            material = parts[1]
        elif tag == "f":
            corners = []
            for corner in parts[1:]:
                indices = []
                for value, count in zip((corner.split("/") + ["", ""])[:3], (len(vertices), len(texcoords), len(normals))):
                    if value == "":
                        indices.append(None)
                    else:
                        i = int(value)
                        indices.append(i - 1 if i > 0 else count + i)
                corners.append(tuple(indices))
            faces.append((group, material, corners))
    return vertices, texcoords, normals, faces


def write_obj(path: Path, faces, vertices, texcoords, normals, offset=(0.0, 0.0, 0.0)) -> None:
    """Writes the faces with their own (renumbered) vertex lists, in Webots coordinates."""
    remap = [{}, {}, {}]
    out_v, out_vt, out_vn, out_f = [], [], [], []
    current_material = None
    for _, material, corners in faces:
        if material != current_material:
            out_f.append(f"usemtl {material}")
            current_material = material
        refs = []
        for corner in corners:
            ref = []
            for kind, index in enumerate(corner):
                if index is None:
                    ref.append("")
                    continue
                if index not in remap[kind]:
                    remap[kind][index] = len(remap[kind]) + 1
                    if kind == 0:
                        x, y, z = to_webots(*vertices[index])
                        out_v.append(f"v {x - offset[0]:.6f} {y - offset[1]:.6f} {z - offset[2]:.6f}")
                    elif kind == 1:
                        out_vt.append("vt " + " ".join(texcoords[index]))
                    else:
                        out_vn.append("vn {:.6f} {:.6f} {:.6f}".format(*rotate_normal(*normals[index])))
                ref.append(str(remap[kind][index]))
            refs.append("/".join(ref).rstrip("/"))
        out_f.append("f " + " ".join(refs))

    lines = ["# Generated by convert_car_model.py (Webots frame, meters)", "mtllib car.mtl", ""]
    path.write_text("\n".join(lines + out_v + out_vt + out_vn + out_f) + "\n", encoding="utf-8")
    print(f"{path.name}: {len(out_v)} vertices, {sum(1 for f in out_f if f.startswith('f '))} faces")


def main() -> None:
    OUTPUT_DIR.mkdir(exist_ok=True)
    vertices, texcoords, normals, faces = read_obj(SOURCE_OBJ)

    wheel_center = to_webots(0.0, WHEEL_CENTER_Y, AXLE_Z)
    wheel_groups = set().union(*WHEEL_GROUPS.values())
    write_obj(OUTPUT_DIR / "car_body.obj", [f for f in faces if f[0] not in wheel_groups],
              vertices, texcoords, normals)
    for filename, groups in WHEEL_GROUPS.items():
        side_x = WHEEL_CENTER_X if "right" in filename else -WHEEL_CENTER_X
        center = to_webots(side_x, WHEEL_CENTER_Y, AXLE_Z)
        write_obj(OUTPUT_DIR / filename, [f for f in faces if f[0] in groups],
                  vertices, texcoords, normals, offset=center)
    print(f"Wheel centers at x={wheel_center[0]:.4f}, y=±{WHEEL_CENTER_X / 1000:.4f}, z={wheel_center[2]:.4f}")

    # The texture maps the .mtl points to were not exported, so drop them
    mtl = [line for line in SOURCE_MTL.read_text(encoding="utf-8", errors="replace").splitlines()
           if not line.startswith("map_")]
    (OUTPUT_DIR / "car.mtl").write_text("\n".join(mtl) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
